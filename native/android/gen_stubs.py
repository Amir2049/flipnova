#!/usr/bin/env python3
"""Write an assembly stub for one of Android's system libraries (libc.so, libm.so, libdl.so) from bionic's symbol map.

  python3 gen_stubs.py <bionic>/libc/libc.map.txt <api level> out.S

The stub library only exists at link time: it gives our .so a DT_NEEDED entry for the real system library and lets the
linker check that every function we call exists on the device (for arm64 at the given API level). Symbols for other
architectures, platform-private ones and ones newer than the API level are left out.
"""
import re
import sys

ARCHES = {"arm", "arm64", "x86", "x86_64", "riscv64"}
SKIP_BLOCK_TAGS = {"platform-only", "llndk", "apex", "systemapi"}
SKIP_BLOCKS = {"LIBC_PRIVATE", "LIBC_PLATFORM", "LIBC_DEPRECATED"}
CODENAMES = {"L": 21, "L-MR1": 22, "M": 23, "N": 24, "N-MR1": 25, "O": 26, "O-MR1": 27, "P": 28, "Q": 29, "R": 30,
             "S": 31, "Sv2": 32, "T": 33, "U": 34, "V": 35}


def level(v):
    return CODENAMES[v] if v in CODENAMES else int(v)


def parse_tags(comment):
    tags = comment.split()
    introduced = None
    arches = set()
    other = set()
    for t in tags:
        if t.startswith("introduced-arm64="):
            introduced = level(t.split("=", 1)[1])
        elif t.startswith("introduced=") and introduced is None:
            introduced = level(t.split("=", 1)[1])
        elif t.startswith("introduced-"):
            pass  # another architecture's level
        elif t in ARCHES:
            arches.add(t)
        else:
            other.add(t)
    return introduced, arches, other


def symbols(path, api):
    out = []
    block = None
    block_ok = True
    block_intro = None
    for raw in open(path):
        line = raw.strip()
        if not line:
            continue
        m = re.match(r"^([A-Z0-9_]+)\s*\{(.*)$", line)
        if m:
            block = m.group(1)
            comment = m.group(2).split("#", 1)[1] if "#" in m.group(2) else ""
            intro, arches, other = parse_tags(comment)
            block_ok = (block not in SKIP_BLOCKS and not (other & SKIP_BLOCK_TAGS)
                        and (not arches or "arm64" in arches))
            block_intro = intro
            continue
        if line.startswith("}") or line.endswith(":") or line.startswith("#") or block is None:
            continue
        if not block_ok:
            continue
        code, _, comment = line.partition("#")
        name = code.strip().rstrip(";").strip()
        if not name or name == "*":
            continue
        intro, arches, other = parse_tags(comment)
        if arches and "arm64" not in arches:
            continue
        if other & SKIP_BLOCK_TAGS:
            continue
        if intro is None:
            intro = block_intro
        if intro is not None and intro > api:
            continue
        out.append((name, "var" in other))
    return out


def main(path, api, out_path):
    syms = symbols(path, int(api))
    with open(out_path, "w") as f:
        f.write("// generated by gen_stubs.py\n")
        for name, is_var in sorted(set(syms)):
            if is_var:
                f.write(f".data\n.globl {name}\n.type {name}, %object\n.size {name}, 8\n{name}:\n.quad 0\n")
            else:
                f.write(f".text\n.globl {name}\n.type {name}, %function\n{name}:\nret\n")
    print(f"{out_path}: {len(set(syms))} symbols")


if __name__ == "__main__":
    main(*sys.argv[1:4])
